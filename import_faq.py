def main():
    old, dropped = [], 0
    if os.path.exists(FACTS):
        for line in open(FACTS, encoding="utf-8"):
            line = line.strip()
            if not line:
                continue
            d = json.loads(line)
            if str(d.get("doc_uid", "")).startswith("faq_"):
                dropped += 1
                continue
            old.append(d)

    rows = []
    for i, (q, a, who) in enumerate(FAQ, 1):
        rows.append({
            "doc_uid": "faq_%02d" % i,
            "chunk_id": 1,
            "source": "faq",
            "title": q,
            "date": DATE,
            "year": 2026,
            "dept": DEPT,
            "tag": "答疑·%s" % who,
            "url": "",
            "printed_page": None,
            "text": "问：%s\n答：%s" % (q, a),
        })

    with open(FACTS, "w", encoding="utf-8") as f:
        for d in old + rows:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")

    print("旧 faq 条目剔除：%d" % dropped)
    print("保留其他条目：%d" % len(old))
    print("写入 faq 条目：%d" % len(rows))
    print("文件合计：%d 条" % (len(old) + len(rows)))


if __name__ == "__main__":
    main()
